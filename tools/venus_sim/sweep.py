"""Position sweep (oracle 1, docs/FIRMWARE_EQUIVALENCE.md section 2.4): Venus's own position of every
labware and every position in it, for corpus layouts, in headless simulation. Per layout: copy it to
<work>/sweep, add its missing labware to the Venus install (labware_closure, labware_siblings: new
files only, in the manifest), generate a probe (a position call per labware and per position),
sign it, run it, keep the run's trace in <work>/sweep/out/<hash>.out. compare_sweep.py compares.

Position names come from rules.placement.default_positions (Venus's own default-sequence call needs
a sequence-sorting COM component that a plain install lacks); a wrong name shows as a Venus error.

  python sweep.py HASH [HASH ...]        (the repo's Python; Venus runs in paths.PYTHON32)"""
import pathlib
import subprocess
import sys

from paths import CORPUS, PYTHON32, REPO, WORK

HERE = pathlib.Path(__file__).resolve().parent
OUT = WORK / "sweep"
RAW = CORPUS / "raw"
PY = sys.executable
sys.path.insert(0, str(REPO))
from venus_interop.files import layout  # noqa: E402
from venus_interop.files.definitions import DEFAULT_VENUS_LABWARE, DefinitionStore, Rack  # noqa: E402
from venus_interop.plr.venus_deck import corpus_index  # noqa: E402
from venus_interop.rules import placement  # noqa: E402

import sign  # noqa: E402

STORE = DefinitionStore([DEFAULT_VENUS_LABWARE], corpus_index(CORPUS))

PROBE = r'''// Position sweep probe for layout {lay}: Venus's own positions (generated by sweep.py)
#include "HSLDevLib.hsl"
#include "HSLLabwrAccess\\HSLLabwrAccess.hsl"
#include "HSLTrcLib.hsl"
global device ML_STAR ("{lay}", "{inst}", hslTrue);
function dump(variable id) void
{{
   variable x; variable y; variable z; variable r;
   onerror goto Fail;
   HSLLabwrAccess::AbsolutePositionValuesGetForLabwareID(ML_STAR, id, x, y, z, r);
   Trace("LAB|", id, "|", x, "|", y, "|", z, "|", r);
   return;
   Fail:
   {{
      Trace("ERR|", id, "|", err.GetDescription());
      return;
   }}
}}
function pos(variable id, variable pid) void
{{
   variable p[];
   onerror goto Fail;
   ML_STAR.GetLabwarePosition(id, p, pid);
   Trace("POS|", id, "|", pid, "|", p[0], "|", p[1], "|", p[2], "|", p[3]);
   return;
   Fail:
   {{
      Trace("ERR|", id, "|", pid, "|", err.GetDescription());
      return;
   }}
}}
method main() void
{{
{calls}
}}
'''


def stage(h: str) -> pathlib.Path:
  src = RAW / f"{h}.lay"
  lay = layout.read_layout(src)
  name = f"L_{h}.lay"
  (OUT / name).write_bytes(src.read_bytes())
  subprocess.run([PY, str(HERE / "labware_closure.py"), str(src), "--copy"], cwd=HERE, capture_output=True, text=True)
  subprocess.run([PY, str(HERE / "labware_siblings.py")], cwd=HERE, capture_output=True, text=True)
  calls = []
  for p in lay.labware:
    i = p.fields.get("Id")
    if not i:
      continue
    calls.append(f'   dump("{i}");')
    d = STORE.get(p.file)
    if isinstance(d, Rack):
      try:
        names = placement.default_positions(d)
      except placement.UnsupportedNaming:
        names = []
      calls += [f'   pos("{i}", "{n}");' for n in names]
  probe = OUT / f"P_{h}.hsl"
  probe.write_text(PROBE.format(lay=name, inst=getattr(lay, "instrument", None) or "ML_STAR", calls="\n".join(calls)),
                   encoding="latin-1")
  sign.sign(probe)
  return probe


def run(h: str, timeout: int = 240) -> str:
  OUT.joinpath("out").mkdir(parents=True, exist_ok=True)
  lib = OUT / "HSLLabwrAccess"
  if not lib.exists():  # the include, from NIST's repository (Venus's install lacks it)
    import shutil
    from paths import NIST
    shutil.copytree(NIST / "Library" / "HSLLabwrAccess", lib)
  probe = stage(h)
  r = subprocess.run([str(PYTHON32), str(HERE / "run_probe.py"), str(probe), str(timeout)],
                     cwd=HERE, capture_output=True, text=True, encoding="latin-1", errors="replace")
  out = r.stdout + r.stderr
  (OUT / "out" / f"{h}.out").write_text(out, encoding="latin-1")
  labs, pos, errs = out.count("; LAB|"), out.count("; POS|"), out.count("; ERR|")
  ended = "End method - complete" in out
  return f"{h}: {'ok' if ended else 'NOT COMPLETE'} labware {labs} positions {pos} errors {errs}"


if __name__ == "__main__":
  for h in sys.argv[1:]:
    print(run(h), flush=True)
